    CREATED_TIME  TIMESTAMP NULL COMMENT '创建时间',
    UPDATED_USER  VARCHAR(32) NULL COMMENT '更新人',
    UPDATED_TIME  TIMESTAMP NULL COMMENT '更新时间'
) COMMENT '退货信息表';
